#!/usr/bin/env python3
"""Generate pdf_oxide's bundled code -> CID tables for the Adobe-Japan1
predefined CMaps (ISO 32000-1 Table 118).

Exception-build tool (see CHANGELOG, .claude/rules/versioning.md). It writes
`src/fonts/predefined_cmap.rs` in the sibling pdf_oxide checkout.

    python3 tools/gen_predefined_cmaps.py <dir with Adobe CMap files> <predefined_cmap.rs>

The CMap files are the ones Adobe publishes in
https://github.com/adobe-type-tools/cmap-resources (Adobe-Japan1-7/CMap/,
BSD-3-Clause). Only codes of one or two bytes are kept: the caller's code
iterator yields 16-bit codes, so a four-byte UTF-16 surrogate pair is out of
its reach. A `-V` CMap stores only what it changes and names its base, as the
source file does with `usecmap`.
"""
import os
import re
import sys

# Table 118, Japanese rows (plus the half-width UCS2 pair Adobe ships).
NAMES = [
    "83pv-RKSJ-H", "90ms-RKSJ-H", "90ms-RKSJ-V", "90msp-RKSJ-H", "90msp-RKSJ-V",
    "90pv-RKSJ-H", "Add-RKSJ-H", "Add-RKSJ-V", "EUC-H", "EUC-V",
    "Ext-RKSJ-H", "Ext-RKSJ-V", "H", "V",
    "UniJIS-UCS2-H", "UniJIS-UCS2-V", "UniJIS-UCS2-HW-H", "UniJIS-UCS2-HW-V",
    "UniJIS-UTF16-H", "UniJIS-UTF16-V", "UniJIS2004-UTF16-H", "UniJIS2004-UTF16-V",
]


def parse(path):
    """-> (base name or None, {code value: cid}) for codes of 1 or 2 bytes."""
    text = open(path, encoding="latin-1").read()
    m = re.search(r"/([A-Za-z0-9-]+)\s+usecmap", text)
    base = m.group(1) if m else None
    codes = {}
    lengths = {}

    def put(hexcode, offset, cid):
        if len(hexcode) > 4:
            return  # 3- and 4-byte codes: not representable in a u16 code
        value = int(hexcode, 16) + offset
        nbytes = len(hexcode) // 2
        if lengths.setdefault(value, nbytes) != nbytes:
            sys.exit("%s: code value %#x is both a 1- and a 2-byte code" % (path, value))
        codes[value] = cid

    for block in re.findall(r"begincidchar(.*?)endcidchar", text, re.S):
        for code, cid in re.findall(r"<([0-9A-Fa-f]+)>\s+(\d+)", block):
            put(code, 0, int(cid))
    for block in re.findall(r"begincidrange(.*?)endcidrange", text, re.S):
        for lo, hi, cid in re.findall(r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s+(\d+)", block):
            for i in range(int(hi, 16) - int(lo, 16) + 1):
                put(lo, i, int(cid) + i)
    return base, codes


def runs(codes):
    """Maximal runs in which code and CID both rise by one: (first, last, cid)."""
    out = []
    for code in sorted(codes):
        cid = codes[code]
        if out and out[-1][1] + 1 == code and out[-1][2] + (code - out[-1][0]) == cid:
            out[-1][1] = code
        else:
            out.append([code, code, cid])
    return out


def ident(name):
    return "CMAP_" + re.sub(r"[^A-Za-z0-9]", "_", name).upper()


