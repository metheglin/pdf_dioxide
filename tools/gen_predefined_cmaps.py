def main(cmap_dir, out_path):
    parsed = {name: parse(os.path.join(cmap_dir, name)) for name in NAMES}
    out = [HEADER]
    out.append("/// The CMap names bundled here.\n")
    out.append("#[cfg(test)]\nconst NAMES: [&str; %d] = [\n" % len(NAMES))
    out += ['    "%s",\n' % n for n in NAMES]
    out.append("];\n\n")
    out.append(
        "/// The bundled CMap of that name, or `None` for a name not bundled here\n"
        "/// (Identity-H/V, the other collections' CMaps, anything unknown).\n"
        "pub(crate) fn lookup(name: &str) -> Option<PredefinedCMap> {\n"
        "    let (runs, base): (&'static [Run], Option<&'static [Run]>) = match name {\n"
    )
    for name in NAMES:
        base = parsed[name][0]
        if base is not None and base not in parsed:
            sys.exit("%s: base %s is not bundled" % (name, base))
        if base is not None and parsed[base][0] is not None:
            sys.exit("%s: base %s has a base of its own" % (name, base))
        out.append(
            '        "%s" => (&%s, %s),\n'
            % (name, ident(name), "Some(&%s)" % ident(base) if base else "None")
        )
    out.append("        _ => return None,\n    };\n    Some(PredefinedCMap { runs, base })\n}\n")
    total = 0
    for name in NAMES:
        rs = runs(parsed[name][1])
        total += len(rs)
        out.append("\n#[rustfmt::skip]\nstatic %s: [Run; %d] = [\n" % (ident(name), len(rs)))
        line = "   "
        for first, last, cid in rs:
            item = " (0x%04X, 0x%04X, %d)," % (first, last, cid)
            if len(line) + len(item) > 100:
                out.append(line + "\n")
                line = "   "
            line += item
        if line.strip():
            out.append(line + "\n")
        out.append("];\n")
    out.append(TESTS)
    open(out_path, "w").write("".join(out))
    print("%d CMaps, %d runs -> %s" % (len(NAMES), total, out_path))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
